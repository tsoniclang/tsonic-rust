import assert from "node:assert/strict";
import { test } from "node:test";

import { printRustSourceFile } from "../dist/index.js";

const headerComment = "Generated by the Tsonic Rust target. Do not edit.";

test("fitting method-call arguments remain on one rustfmt line", () => {
  const source = printRustSourceFile({
    headerComment,
    items: [{
      kind: "function",
      name: "proof",
      visibility: "public",
      params: [],
      body: {
        statements: [{
          kind: "expr",
          expr: {
            kind: "call",
            path: "acme_testing::check",
            args: [{
              kind: "method-call",
              receiver: {
                kind: "call",
                path: "tsonic_rust_node::process::env_get",
                args: [{ kind: "str-literal", value: "R7_UNSET_VAR_PROOF" }],
              },
              method: "is_none",
              args: [],
            }],
          },
        }],
      },
    }],
  });

  assert.match(
    source,
    /acme_testing::check\(tsonic_rust_node::process::env_get\("R7_UNSET_VAR_PROOF"\)\.is_none\(\)\);/u,
  );
});

